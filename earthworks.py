def get_goals_by_type(work_type: str) -> dict:
    """Получить список целей по типу работы"""
    if work_type == "order":
        return ORDER_GOALS
    elif work_type == "mpgu_planned":
        return MPGU_PLANNED_GOALS
    elif work_type == "iasugd_planned":
        return IASUGD_PLANNED_GOALS
    return {}


def search_npa_answer(query: str) -> dict:
    """Поиск ответа в базе знаний НПА"""
    query_lower = query.lower()
    
    # Простой поиск по ключевым словам
    best_match = None
    max_score = 0
    
    for key, item in NPA_KNOWLEDGE_BASE.items():
        score = 0
        question_words = item["question"].lower().split()
        answer_words = item["answer"].lower().split()
        
        # Подсчет совпадений
        for word in query_lower.split():
            if len(word) < 3:
                continue
            if word in question_words:
                score += 2
            if word in answer_words:
                score += 1
            if word in key:
                score += 3
        
        if score > max_score:
            max_score = score
            best_match = item
    
    return best_match if max_score > 0 else None


def format_npa_answer(item: dict) -> str:
    """Форматирование ответа из НПА"""
    return f"<b>Вопрос:</b> {item['question']}\n\n{item['answer']}\n\n📚 Источник: Постановление Правительства Москвы {item['source']}"
