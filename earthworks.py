def get_goals_by_type(work_type: str) -> dict:
    """Получить список целей по типу работы"""
    if work_type == "order":
        return ORDER_GOALS
    elif work_type == "mpgu_planned":
        return MPGU_PLANNED_GOALS
    elif work_type == "iasugd_planned":
        return IASUGD_PLANNED_GOALS
    return {}


