def get_ai_response(question: str) -> str:
    """Получить ответ от AI-ассистента"""
    # Заглушка для AI-ассистента
    # В реальной реализации здесь будет интеграция с OpenAI API или другим AI сервисом
    
    responses = {
        "возможности": "✨ Наши возможности:\n• Конвертация документов (PDF, Word, Excel)\n• OCR распознавание текста\n• AI-ассистент 24/7\n• Шаблоны документов\n• Личный кабинет с статистикой",
        "преимущества": "🏆 Наши преимущества:\n• Быстрая обработка документов\n• Высокая точность OCR\n• Круглосуточная поддержка\n• Безопасность данных\n• Доступные тарифы",
        "тарифы": "💎 Тарифы:\n• Базовый: 299₽/мес (10 документов)\n• Профессиональный: 799₽/мес (50 документов)\n• Бизнес: 1999₽/мес (безлимит)\n\nАктивируйте триал на 7 дней бесплатно!"
    }
    
    question_lower = question.lower()
    
    if "возможност" in question_lower:
        return responses["возможности"]
    elif "преимущ" in question_lower:
        return responses["преимущества"]
    elif "тариф" in question_lower or "цен" in question_lower:
        return responses["тарифы"]
    else:
        return "🤖 AI-ассистент готов помочь! Задайте вопрос о возможностях, преимуществах или тарифах нашего сервиса."


