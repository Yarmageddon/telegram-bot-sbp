# ═══════════════════════════════════════════════════════════════
# УТИЛИТЫ
# ═══════════════════════════════════════════════════════════════

def get_agent(agent_id: str) -> Optional[AgentConfig]:
    return AGENTS.get(agent_id)


def get_available_agents() -> list[AgentConfig]:
    return [a for a in AGENTS.values() if a.is_available]


def get_agent_menu_items() -> list[tuple[str, str]]:
    """Список (callback_data, label) для плоского меню."""
    return [
        (f"agent:{a.id}", f"{a.emoji} {a.name}")
        for a in get_available_agents()
    ]


