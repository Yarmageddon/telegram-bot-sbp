# ── Утилиты ──────────────────────────────────────────────────────

def get_agent(agent_id: str) -> Optional[AgentConfig]:
    """Получить агента по ID."""
    return AGENTS.get(agent_id)


def get_available_agents() -> list[AgentConfig]:
    """Получить список всех доступных агентов."""
    return [a for a in AGENTS.values() if a.is_available]


def get_agents_by_category(category: str) -> list[AgentConfig]:
    """Получить агентов по категории."""
    return [a for a in AGENTS.values() if a.category == category and a.is_available]


def get_categories() -> list[str]:
    """Получить список всех категорий (в порядке появления)."""
    seen = []
    for agent in AGENTS.values():
        if agent.category not in seen:
            seen.append(agent.category)
    return seen


def get_category_title(category: str) -> str:
    """Человекочитаемое название категории."""
    titles = {
        "productivity": "🗂️ Продуктивность",
        "info": "📡 Информация",
        "health": "💚 Здоровье",
        "work": "💼 Работа и знания",
        "home": "🏡 Дом и сад",
    }
    return titles.get(category, category)


def get_agent_menu_items() -> list[tuple[str, str]]:
    """Вернуть плоский список (callback_data, label) для простой клавиатуры."""
    return [
        (f"agent:{a.id}", f"{a.emoji} {a.name}")
        for a in get_available_agents()
    ]


def get_agent_menu_items_grouped() -> list[tuple[str, list[tuple[str, str]]]]:
    """Вернуть список категорий с их агентами для группированной клавиатуры."""
    result = []
    for category in get_categories():
        agents_in_cat = get_agents_by_category(category)
        if agents_in_cat:
            items = [(f"agent:{a.id}", f"{a.emoji} {a.name}") for a in agents_in_cat]
            result.append((get_category_title(category), items))
    return result


