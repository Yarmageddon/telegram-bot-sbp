@dataclass
class AgentButton:
    """Кнопка меню агента."""
    label: str                    # текст кнопки
    prompt: str                   # что отправить в LLM при нажатии
    action: str = ""              # спец-действие: "" | "upload_file"


@dataclass
class AgentConfig:
    """Конфигурация одного агента."""
    id: str
    name: str
    emoji: str
    description: str
    system_prompt: str
    category: str
    temperature: float = 0.7
    tools: list[str] = field(default_factory=list)
    menu_buttons: list[AgentButton] = field(default_factory=list)
    is_available: bool = True


